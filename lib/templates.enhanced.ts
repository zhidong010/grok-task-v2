// 根据难度筛选
export function filterByDifficulty(templates: Template[], difficulty: Template['difficulty']): Template[] {
  return templates.filter((t) => t.difficulty === difficulty);
}

// 根据分类筛选
export function filterByCategory(templates: Template[], category: string): Template[] {
  if (category === 'all') return templates;
  return templates.filter((t) => t.category === category);
}

// 搜索模板
export function searchTemplates(templates: Template[], query: string): Template[] {
  const lowerQuery = query.toLowerCase();
  return templates.filter(
    (t) =>
      t.name.toLowerCase().includes(lowerQuery) ||
      t.description.toLowerCase().includes(lowerQuery) ||
      t.tags?.some((tag) => tag.toLowerCase().includes(lowerQuery))
  );
}
